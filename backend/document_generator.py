class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' numbering."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))
        # Running footer
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 46, 32, page_text)
        self.drawString(46, 32, "Confidential — Generated by Autonomous Windows OS Assistant")
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(46, 44, 612 - 46, 44)
        self.restoreState()


class DocumentGenerator:
    def __init__(self, output_dir: Optional[Path] = None):
        self.output_dir = output_dir or OUTPUT_DOCS_DIR

    def _resolve_output_path(self, filename: str, ext: str) -> Path:
        if not filename.endswith(ext):
            filename = f"{filename}{ext}"
        target = Path(filename)
        if not target.is_absolute():
            target = (self.output_dir / target).resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        return target

    # =========================================================================
    # 1. POWERPOINT PRESENTATION GENERATOR (.pptx)
    # =========================================================================
    def create_presentation(
        self,
        topic: str,
        filename: Optional[str] = None,
        slides_data: Optional[List[Dict[str, Any]]] = None,
        theme: str = "cyber_sapphire"
    ) -> Dict[str, Any]:
        """
        Generates a widescreen (16:9) PowerPoint presentation with rich styling,
        custom card layouts, accent highlights, and professional typography.
        """
        if not filename:
            clean_topic = "".join(c for c in topic if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            filename = f"{clean_topic[:30]}_Presentation.pptx"

        out_path = self._resolve_output_path(filename, ".pptx")

        prs = Presentation()
        # Set 16:9 widescreen dimensions
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)
        blank_slide_layout = prs.slide_layouts[6]

        # Theme Color Palettes
        if theme == "cyber_sapphire":
            c_bg = RGBColor(11, 15, 25)         # Deep Space Navy #0b0f19
            c_card = RGBColor(22, 30, 49)       # Dark Sapphire #161e31
            c_card_border = RGBColor(38, 52, 84)# Subtle Slate
            c_accent = RGBColor(6, 182, 212)    # Electric Cyan #06b6d4
            c_accent2 = RGBColor(99, 102, 241)  # Neon Indigo #6366f1
            c_text_main = RGBColor(248, 250, 252) # Crisp White
            c_text_muted = RGBColor(148, 163, 184) # Muted Slate
            c_header_bar = RGBColor(14, 165, 233)
        elif theme == "academic_clean":
            c_bg = RGBColor(248, 250, 252)
            c_card = RGBColor(255, 255, 255)
            c_card_border = RGBColor(226, 232, 240)
            c_accent = RGBColor(14, 116, 144)
            c_accent2 = RGBColor(59, 130, 246)
            c_text_main = RGBColor(15, 23, 42)
            c_text_muted = RGBColor(71, 85, 105)
            c_header_bar = RGBColor(14, 116, 144)
        else: # modern dark
            c_bg = RGBColor(15, 23, 42)
            c_card = RGBColor(30, 41, 59)
            c_card_border = RGBColor(51, 65, 85)
            c_accent = RGBColor(16, 185, 129)
            c_accent2 = RGBColor(14, 165, 233)
            c_text_main = RGBColor(241, 245, 249)
            c_text_muted = RGBColor(148, 163, 184)
            c_header_bar = RGBColor(16, 185, 129)

        # Build default structured slides if not provided
        if not slides_data:
            slides_data = self._generate_default_slides_data(topic)

        # Helper to set solid background on slide
        def set_slide_background(slide):
            bg_shape = slide.shapes.add_shape(
                MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), prs.slide_width, prs.slide_height
            )
            bg_shape.fill.solid()
            bg_shape.fill.fore_color.rgb = c_bg
            bg_shape.line.fill.background() # no border

        # ---------------- SLIDE 1: TITLE SLIDE ----------------
        title_slide = prs.slides.add_slide(blank_slide_layout)
        set_slide_background(title_slide)

        # Decorative Accent Bar
        accent_bar = title_slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, Inches(1.2), Inches(1.8), Inches(0.12), Inches(3.6)
        )
        accent_bar.fill.solid()
        accent_bar.fill.fore_color.rgb = c_accent
        accent_bar.line.fill.background()

        # Title Box
        title_box = title_slide.shapes.add_textbox(Inches(1.5), Inches(1.7), Inches(10.5), Inches(3.8))
        tf = title_box.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_top = tf.margin_right = tf.margin_bottom = 0

        p_badge = tf.paragraphs[0]
        p_badge.text = "OFFICIAL PRESENTATION & EXECUTIVE BRIEFING"
        p_badge.font.name = "Segoe UI"
        p_badge.font.size = Pt(11)
        p_badge.font.bold = True
        p_badge.font.color.rgb = c_accent2
        p_badge.space_after = Pt(14)

        p_title = tf.add_paragraph()
        p_title.text = slides_data[0].get("title", topic.title())
        p_title.font.name = "Segoe UI"
        p_title.font.size = Pt(40)
        p_title.font.bold = True
        p_title.font.color.rgb = c_text_main
        p_title.space_after = Pt(12)

        p_sub = tf.add_paragraph()
        p_sub.text = slides_data[0].get("subtitle", f"Comprehensive analysis, key pillars, and strategic insights for {topic}")
        p_sub.font.name = "Segoe UI"
        p_sub.font.size = Pt(18)
        p_sub.font.color.rgb = c_text_muted

        # Presenter Card at Bottom
        info_card = title_slide.shapes.add_shape(
            MSO_SHAPE.ROUNDED_RECTANGLE, Inches(1.5), Inches(5.8), Inches(7.5), Inches(0.9)
        )
        info_card.fill.solid()
        info_card.fill.fore_color.rgb = c_card
        info_card.line.color.rgb = c_card_border
        info_card.line.width = Pt(1)

        ic_tf = info_card.text_frame
        ic_tf.word_wrap = True
        ic_tf.margin_left = Inches(0.2)
        ic_tf.margin_top = Inches(0.15)
        p_ic = ic_tf.paragraphs[0]
        p_ic.text = f"Prepared by: Autonomous Multi-Agent OS Assistant  |  Date: {datetime.now().strftime('%B %d, %Y')}"
        p_ic.font.name = "Segoe UI"
        p_ic.font.size = Pt(11)
        p_ic.font.color.rgb = c_text_muted

        # ---------------- SUBSEQUENT SLIDES ----------------
        for slide_idx, sdata in enumerate(slides_data[1:], start=2):
            slide = prs.slides.add_slide(blank_slide_layout)
            set_slide_background(slide)

            # Top Header Bar
            h_box = slide.shapes.add_textbox(Inches(0.9), Inches(0.6), Inches(11.5), Inches(1.1))
            htf = h_box.text_frame
            htf.word_wrap = True
            htf.margin_left = htf.margin_top = 0

            p_cat = htf.paragraphs[0]
            p_cat.text = f"SECTION 0{slide_idx - 1} // EXECUTIVE OVERVIEW"
            p_cat.font.name = "Segoe UI"
            p_cat.font.size = Pt(9.5)
            p_cat.font.bold = True
            p_cat.font.color.rgb = c_accent
            p_cat.space_after = Pt(4)

            p_stitle = htf.add_paragraph()
            p_stitle.text = sdata.get("title", f"Key Insights {slide_idx}")
            p_stitle.font.name = "Segoe UI"
            p_stitle.font.size = Pt(24)
            p_stitle.font.bold = True
            p_stitle.font.color.rgb = c_text_main

            # Thin Accent Line
            line = slide.shapes.add_shape(
                MSO_SHAPE.RECTANGLE, Inches(0.9), Inches(1.8), Inches(11.5), Inches(0.02)
            )
            line.fill.solid()
            line.fill.fore_color.rgb = c_card_border
            line.line.fill.background()

            # Render Cards Layout
            cards = sdata.get("cards", [])
            bullets = sdata.get("bullets", [])

            if cards:
                # 2, 3 or 4 Column Bento Cards
                num_cards = min(len(cards), 3)
                gap = Inches(0.3)
                total_w = Inches(11.5)
                card_w = (total_w - (gap * (num_cards - 1))) / num_cards
                card_h = Inches(4.7)

                for c_i, card in enumerate(cards[:num_cards]):
                    cx = Inches(0.9) + c_i * (card_w + gap)
                    cy = Inches(2.1)

                    card_shape = slide.shapes.add_shape(
                        MSO_SHAPE.ROUNDED_RECTANGLE, cx, cy, card_w, card_h
                    )
                    card_shape.fill.solid()
                    card_shape.fill.fore_color.rgb = c_card
                    card_shape.line.color.rgb = c_card_border
                    card_shape.line.width = Pt(1)

                    ctf = card_shape.text_frame
                    ctf.word_wrap = True
                    ctf.margin_left = ctf.margin_right = Inches(0.25)
                    ctf.margin_top = Inches(0.3)

                    # Card Badge
                    p_num = ctf.paragraphs[0]
                    p_num.text = f"0{c_i + 1}"
                    p_num.font.name = "Segoe UI"
                    p_num.font.size = Pt(16)
                    p_num.font.bold = True
                    p_num.font.color.rgb = c_accent
                    p_num.space_after = Pt(8)

                    # Card Title
                    p_ctitle = ctf.add_paragraph()
                    p_ctitle.text = card.get("title", f"Pillar {c_i+1}")
                    p_ctitle.font.name = "Segoe UI"
                    p_ctitle.font.size = Pt(16)
                    p_ctitle.font.bold = True
                    p_ctitle.font.color.rgb = c_text_main
                    p_ctitle.space_after = Pt(12)

                    # Card Description / Points
                    desc = card.get("description", "")
                    if desc:
                        p_cdesc = ctf.add_paragraph()
                        p_cdesc.text = desc
                        p_cdesc.font.name = "Segoe UI"
                        p_cdesc.font.size = Pt(11.5)
                        p_cdesc.font.color.rgb = c_text_muted
                        p_cdesc.space_after = Pt(8)

                    for point in card.get("points", []):
                        p_p = ctf.add_paragraph()
                        p_p.text = f"• {point}"
                        p_p.font.name = "Segoe UI"
                        p_p.font.size = Pt(11)
                        p_p.font.color.rgb = c_text_muted
                        p_p.space_after = Pt(4)

            elif bullets:
                # 2-column or list layout
                box = slide.shapes.add_textbox(Inches(1.0), Inches(2.2), Inches(11.3), Inches(4.5))
                btf = box.text_frame
                btf.word_wrap = True

                for b_i, b in enumerate(bullets):
                    p = btf.paragraphs[0] if b_i == 0 else btf.add_paragraph()
                    p.text = f"▸  {b}"
                    p.font.name = "Segoe UI"
                    p.font.size = Pt(14)
                    p.font.color.rgb = c_text_main
                    p.space_after = Pt(14)

            # Footer on each slide
            ft_box = slide.shapes.add_textbox(Inches(0.9), Inches(6.9), Inches(11.5), Inches(0.4))
            ftf = ft_box.text_frame
            p_ft = ftf.paragraphs[0]
            p_ft.text = f"{topic.upper()}  |  SLIDE {slide_idx} OF {len(slides_data)}"
            p_ft.font.name = "Segoe UI"
            p_ft.font.size = Pt(8.5)
            p_ft.font.color.rgb = c_text_muted

        prs.save(str(out_path))
        file_size = out_path.stat().st_size

        doc_id = f"doc-pptx-{uuid.uuid4().hex[:8]}"
        try:
            save_generated_document(
                doc_id=doc_id,
                filename=out_path.name,
                file_path=str(out_path),
                file_type="PPTX",
                topic=topic,
                size_bytes=file_size
            )
        except Exception as e:
            logger.warning(f"Could not register presentation in DB: {e}")

        logger.info(f"Generated PowerPoint presentation: {out_path} ({file_size} bytes)")
        return {
            "success": True,
            "doc_id": doc_id,
            "path": str(out_path),
            "filename": out_path.name,
            "topic": topic,
            "slides_count": len(slides_data),
            "file_size": file_size,
            "message": f"PowerPoint presentation '{out_path.name}' created with {len(slides_data)} styled slides."
        }

    # =========================================================================
    # 2. EXECUTIVE PDF REPORT GENERATOR (.pdf)
    # =========================================================================
    def create_pdf_report(
        self,
        title: str,
        filename: Optional[str] = None,
        sections: Optional[List[Dict[str, Any]]] = None,
        executive_summary: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates a publication-grade PDF report with cover header,
        styled callout box, structured multi-section text, data tables, and dynamic footer.
        """
        if not filename:
            clean_title = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            filename = f"{clean_title[:30]}_Report.pdf"

        out_path = self._resolve_output_path(filename, ".pdf")

        if not sections:
            sections = self._generate_default_pdf_sections(title)
        if not executive_summary:
            executive_summary = (
                f"This comprehensive executive report provides an in-depth operational and architectural analysis "
                f"of {title}. It explores foundational methodologies, core performance benchmarks, implementation "
                f"strategies, and future growth trajectories."
            )

        doc = SimpleDocTemplate(
            str(out_path),
            pagesize=letter,
            leftMargin=46,
            rightMargin=46,
            topMargin=46,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        style_title = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=6
        )

        style_subtitle = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=16
        )

        style_h1 = ParagraphStyle(
            "Heading1_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#0284c7"),
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True
        )

        style_h2 = ParagraphStyle(
            "Heading2_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=11.5,
            leading=15,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=10,
            spaceAfter=4,
            keepWithNext=True
        )

        style_body = ParagraphStyle(
            "Body_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8
        )

        style_bullet = ParagraphStyle(
            "Bullet_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            leftIndent=14,
            spaceAfter=4
        )

        style_callout = ParagraphStyle(
            "Callout_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#0f172a")
        )

        story = []

        # 1. Document Header
        story.append(Paragraph(title, style_title))
        meta_line = f"Publication Date: {datetime.now().strftime('%B %d, %Y')}   |   Status: Verified Report   |   System: AI OS Platform"
        story.append(Paragraph(meta_line, style_subtitle))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceBefore=0, spaceAfter=14))

        # 2. Executive Summary Callout Box
        summary_inner = [
            [Paragraph("<b>EXECUTIVE SUMMARY</b>", ParagraphStyle("ES_H", fontName="Helvetica-Bold", fontSize=10, textColor=colors.HexColor("#0369a1")))],
            [Paragraph(executive_summary, style_callout)]
        ]
        summary_table = Table(summary_inner, colWidths=[520])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#f0f9ff")),
            ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#bae6fd")),
            ('LINELEFT', (0,0), (0,-1), 3.5, colors.HexColor("#0284c7")),
            ('PADDING', (0,0), (-1,-1), 8),
            ('BOTTOMPADDING', (0,0), (-1,0), 4),
        ]))
        story.append(summary_table)
        story.append(Spacer(1, 14))

        # 3. Dynamic Sections
        for sec in sections:
            story.append(Paragraph(sec.get("heading", "Section Overview"), style_h1))
            sec_text = sec.get("text", "")
            if sec_text:
                story.append(Paragraph(sec_text, style_body))

            # Bullets if any
            for b in sec.get("bullets", []):
                story.append(Paragraph(f"•  {b}", style_bullet))

            # Metric Table if any
            table_data = sec.get("table", None)
            if table_data and len(table_data) > 1:
                story.append(Spacer(1, 4))
                t_rows = []
                for row_idx, r in enumerate(table_data):
                    t_row = []
                    for c in r:
                        font_n = "Helvetica-Bold" if row_idx == 0 else "Helvetica"
                        text_c = colors.HexColor("#ffffff") if row_idx == 0 else colors.HexColor("#1e293b")
                        p = Paragraph(str(c), ParagraphStyle(f"T_{row_idx}", fontName=font_n, fontSize=8.5, leading=11, textColor=text_c))
                        t_row.append(p)
                    t_rows.append(t_row)

                num_cols = len(table_data[0])
                col_w = 520 / num_cols
                rep_table = Table(t_rows, colWidths=[col_w] * num_cols)
                rep_table.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#0f172a")),
                    ('ALIGN', (0,0), (-1,-1), 'LEFT'),
                    ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                    ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#cbd5e1")),
                    ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.HexColor("#ffffff"), colors.HexColor("#f8fafc")]),
                    ('PADDING', (0,0), (-1,-1), 5),
                ]))
                story.append(rep_table)
                story.append(Spacer(1, 8))

        doc.build(story, canvasmaker=NumberedCanvas)
        file_size = out_path.stat().st_size

        doc_id = f"doc-pdf-{uuid.uuid4().hex[:8]}"
        try:
            save_generated_document(
                doc_id=doc_id,
                filename=out_path.name,
                file_path=str(out_path),
                file_type="PDF",
                topic=title,
                size_bytes=file_size
            )
        except Exception as e:
            logger.warning(f"Could not register PDF in DB: {e}")

        logger.info(f"Generated PDF report: {out_path} ({file_size} bytes)")
        return {
            "success": True,
            "doc_id": doc_id,
            "path": str(out_path),
            "filename": out_path.name,
            "title": title,
            "file_size": file_size,
            "message": f"Executive PDF report '{out_path.name}' created with publication-grade formatting."
        }

