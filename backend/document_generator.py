class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' numbering."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))
        # Running footer
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 46, 32, page_text)
        self.drawString(46, 32, "Confidential — Generated by Autonomous Windows OS Assistant")
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(46, 44, 612 - 46, 44)
        self.restoreState()


class DocumentGenerator:
    def __init__(self, output_dir: Optional[Path] = None):
        self.output_dir = output_dir or OUTPUT_DOCS_DIR

    def _resolve_output_path(self, filename: str, ext: str) -> Path:
        if not filename.endswith(ext):
            filename = f"{filename}{ext}"
        target = Path(filename)
        if not target.is_absolute():
            target = (self.output_dir / target).resolve()
        target.parent.mkdir(parents=True, exist_ok=True)

        # Check if target file already exists and is locked by an active application (e.g. PowerPoint, Word, Excel, Acrobat)
        if target.exists():
            try:
                with open(target, "r+b"):
                    pass
            except (PermissionError, OSError):
                stem = target.stem
                parent = target.parent
                for i in range(2, 100):
                    candidate = parent / f"{stem}_v{i}{ext}"
                    try:
                        if candidate.exists():
                            with open(candidate, "r+b"):
                                pass
                        target = candidate
                        logger.warning(
                            f"Target file '{filename}' is currently open and locked by an active program (PowerPoint/Office). "
                            f"Auto-versioning output to '{target.name}'."
                        )
                        break
                    except (PermissionError, OSError):
                        continue

        return target

    # =========================================================================
    # 1. POWERPOINT PRESENTATION GENERATOR (.pptx)
    # =========================================================================
    def create_presentation(
        self,
        topic: str,
        filename: Optional[str] = None,
        slides_data: Optional[List[Dict[str, Any]]] = None,
        theme: str = "cyber_sapphire",
        task_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates a widescreen (16:9) PowerPoint presentation with rich styling,
        custom card layouts, accent highlights, and professional typography.
        """
        if not filename:
            clean_topic = "".join(c for c in topic if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            filename = f"{clean_topic[:30]}_Presentation.pptx"

        out_path = self._resolve_output_path(filename, ".pptx")

        prs = Presentation()
        # Set 16:9 widescreen dimensions
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)
        blank_slide_layout = prs.slide_layouts[6]

        # Theme Color Palettes
        if theme == "cyber_sapphire":
            c_bg = RGBColor(11, 15, 25)         # Deep Space Navy #0b0f19
            c_card = RGBColor(22, 30, 49)       # Dark Sapphire #161e31
            c_card_border = RGBColor(38, 52, 84)# Subtle Slate
            c_accent = RGBColor(6, 182, 212)    # Electric Cyan #06b6d4
            c_accent2 = RGBColor(99, 102, 241)  # Neon Indigo #6366f1
            c_text_main = RGBColor(248, 250, 252) # Crisp White
            c_text_muted = RGBColor(148, 163, 184) # Muted Slate
            c_header_bar = RGBColor(14, 165, 233)
        elif theme == "academic_clean":
            c_bg = RGBColor(248, 250, 252)
            c_card = RGBColor(255, 255, 255)
            c_card_border = RGBColor(226, 232, 240)
            c_accent = RGBColor(14, 116, 144)
            c_accent2 = RGBColor(59, 130, 246)
            c_text_main = RGBColor(15, 23, 42)
            c_text_muted = RGBColor(71, 85, 105)
            c_header_bar = RGBColor(14, 116, 144)
        else: # modern dark
            c_bg = RGBColor(15, 23, 42)
            c_card = RGBColor(30, 41, 59)
            c_card_border = RGBColor(51, 65, 85)
            c_accent = RGBColor(16, 185, 129)
            c_accent2 = RGBColor(14, 165, 233)
            c_text_main = RGBColor(241, 245, 249)
            c_text_muted = RGBColor(148, 163, 184)
            c_header_bar = RGBColor(16, 185, 129)

        # Build default structured slides if not provided
        if not slides_data:
            slides_data = self._generate_default_slides_data(topic)

        # Helper to set solid background on slide
        def set_slide_background(slide):
            bg_shape = slide.shapes.add_shape(
                MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), prs.slide_width, prs.slide_height
            )
            bg_shape.fill.solid()
            bg_shape.fill.fore_color.rgb = c_bg
            bg_shape.line.fill.background() # no border

        # ---------------- SLIDE 1: TITLE SLIDE ----------------
        title_slide = prs.slides.add_slide(blank_slide_layout)
        set_slide_background(title_slide)

        # Decorative Accent Bar
        accent_bar = title_slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, Inches(1.2), Inches(1.8), Inches(0.12), Inches(3.6)
        )
        accent_bar.fill.solid()
        accent_bar.fill.fore_color.rgb = c_accent
        accent_bar.line.fill.background()

        # Title Box
        title_box = title_slide.shapes.add_textbox(Inches(1.5), Inches(1.7), Inches(10.5), Inches(3.8))
        tf = title_box.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_top = tf.margin_right = tf.margin_bottom = 0

        p_badge = tf.paragraphs[0]
        p_badge.text = "OFFICIAL PRESENTATION & EXECUTIVE BRIEFING"
        p_badge.font.name = "Segoe UI"
        p_badge.font.size = Pt(11)
        p_badge.font.bold = True
        p_badge.font.color.rgb = c_accent2
        p_badge.space_after = Pt(14)

        p_title = tf.add_paragraph()
        p_title.text = slides_data[0].get("title", topic.title())
        p_title.font.name = "Segoe UI"
        p_title.font.size = Pt(40)
        p_title.font.bold = True
        p_title.font.color.rgb = c_text_main
        p_title.space_after = Pt(12)

        p_sub = tf.add_paragraph()
        p_sub.text = slides_data[0].get("subtitle", f"Comprehensive analysis, key pillars, and strategic insights for {topic}")
        p_sub.font.name = "Segoe UI"
        p_sub.font.size = Pt(18)
        p_sub.font.color.rgb = c_text_muted

        # Presenter Card at Bottom
        info_card = title_slide.shapes.add_shape(
            MSO_SHAPE.ROUNDED_RECTANGLE, Inches(1.5), Inches(5.8), Inches(7.5), Inches(0.9)
        )
        info_card.fill.solid()
        info_card.fill.fore_color.rgb = c_card
        info_card.line.color.rgb = c_card_border
        info_card.line.width = Pt(1)

        ic_tf = info_card.text_frame
        ic_tf.word_wrap = True
        ic_tf.margin_left = Inches(0.2)
        ic_tf.margin_top = Inches(0.15)
        p_ic = ic_tf.paragraphs[0]
        p_ic.text = f"Prepared by: Autonomous Multi-Agent OS Assistant  |  Date: {datetime.now().strftime('%B %d, %Y')}"
        p_ic.font.name = "Segoe UI"
        p_ic.font.size = Pt(11)
        p_ic.font.color.rgb = c_text_muted

        # ---------------- SUBSEQUENT SLIDES ----------------
        for slide_idx, sdata in enumerate(slides_data[1:], start=2):
            slide = prs.slides.add_slide(blank_slide_layout)
            set_slide_background(slide)

            # Top Header Bar
            h_box = slide.shapes.add_textbox(Inches(0.9), Inches(0.6), Inches(11.5), Inches(1.1))
            htf = h_box.text_frame
            htf.word_wrap = True
            htf.margin_left = htf.margin_top = 0

            p_cat = htf.paragraphs[0]
            p_cat.text = f"SECTION 0{slide_idx - 1} // EXECUTIVE OVERVIEW"
            p_cat.font.name = "Segoe UI"
            p_cat.font.size = Pt(9.5)
            p_cat.font.bold = True
            p_cat.font.color.rgb = c_accent
            p_cat.space_after = Pt(4)

            p_stitle = htf.add_paragraph()
            p_stitle.text = sdata.get("title", f"Key Insights {slide_idx}")
            p_stitle.font.name = "Segoe UI"
            p_stitle.font.size = Pt(24)
            p_stitle.font.bold = True
            p_stitle.font.color.rgb = c_text_main

            # Thin Accent Line
            line = slide.shapes.add_shape(
                MSO_SHAPE.RECTANGLE, Inches(0.9), Inches(1.8), Inches(11.5), Inches(0.02)
            )
            line.fill.solid()
            line.fill.fore_color.rgb = c_card_border
            line.line.fill.background()

            # Render Cards, Table, or Content Layout
            cards = sdata.get("cards", [])
            bullets = sdata.get("bullets", [])
            table_data = sdata.get("table") or sdata.get("matrix")
            content_raw = sdata.get("content", "")

            # Auto-parse unstructured text if structured cards/bullets are absent
            if not cards and not bullets and not table_data and content_raw:
                content_text = str(content_raw).strip()
                item_pattern = re.compile(r'(?:^|\n)\s*(\d+)\.\s+([^\n:]+):?\s*([\s\S]*?)(?=(?:\n\s*\d+\.|\Z))')
                matches = item_pattern.findall(content_text)
                if matches:
                    for num, c_title, c_body in matches:
                        lines = [l.strip() for l in c_body.strip().splitlines() if l.strip()]
                        pts = [re.sub(r'^[\-\*•▸]\s*', '', l) for l in lines if l.startswith(('-', '*', '•', '▸'))]
                        dsc = ' '.join(l for l in lines if not l.startswith(('-', '*', '•', '▸')))
                        cards.append({
                            "title": c_title.strip(),
                            "description": dsc,
                            "points": pts if pts else lines
                        })
                else:
                    raw_lines = [l.strip() for l in content_text.splitlines() if l.strip()]
                    for l in raw_lines:
                        clean_l = re.sub(r'^[\-\*•▸]\s*', '', l).strip()
                        if clean_l:
                            bullets.append(clean_l)

            if table_data and isinstance(table_data, dict) and "headers" in table_data and "rows" in table_data:
                headers = table_data.get("headers", [])
                rows = table_data.get("rows", [])
                num_r = len(rows) + 1
                num_c = len(headers)
                t_w = Inches(11.5)
                t_h = Inches(4.7)
                tbl_shape = slide.shapes.add_table(num_r, num_c, Inches(0.9), Inches(2.1), t_w, t_h)
                tbl = tbl_shape.table
                for ci, h_txt in enumerate(headers):
                    cell = tbl.cell(0, ci)
                    cell.fill.solid()
                    cell.fill.fore_color.rgb = c_card
                    cp = cell.text_frame.paragraphs[0]
                    cp.text = str(h_txt)
                    cp.font.name = "Segoe UI"
                    cp.font.size = Pt(11)
                    cp.font.bold = True
                    cp.font.color.rgb = c_accent
                for ri, row_vals in enumerate(rows, start=1):
                    for ci, val in enumerate(row_vals[:num_c]):
                        cell = tbl.cell(ri, ci)
                        cell.fill.solid()
                        cell.fill.fore_color.rgb = RGBColor(16, 22, 38) if ri % 2 == 1 else RGBColor(12, 17, 30)
                        cp = cell.text_frame.paragraphs[0]
                        cp.text = str(val)
                        cp.font.name = "Segoe UI"
                        cp.font.size = Pt(10)
                        cp.font.color.rgb = c_text_muted

            elif cards:
                # 2, 3, 4, or 5 Column Bento Cards
                num_cards = min(len(cards), 5)
                gap = Inches(0.25) if num_cards >= 4 else Inches(0.3)
                total_w = Inches(11.5)
                card_w = (total_w - (gap * (num_cards - 1))) / num_cards
                card_h = Inches(4.7)

                for c_i, card in enumerate(cards[:num_cards]):
                    cx = Inches(0.9) + c_i * (card_w + gap)
                    cy = Inches(2.1)

                    card_shape = slide.shapes.add_shape(
                        MSO_SHAPE.ROUNDED_RECTANGLE, cx, cy, card_w, card_h
                    )
                    card_shape.fill.solid()
                    card_shape.fill.fore_color.rgb = c_card
                    card_shape.line.color.rgb = c_card_border
                    card_shape.line.width = Pt(1)

                    ctf = card_shape.text_frame
                    ctf.word_wrap = True
                    ctf.margin_left = ctf.margin_right = Inches(0.18) if num_cards >= 4 else Inches(0.25)
                    ctf.margin_top = Inches(0.22)

                    # Card Badge
                    p_num = ctf.paragraphs[0]
                    p_num.text = f"0{c_i + 1}"
                    p_num.font.name = "Segoe UI"
                    p_num.font.size = Pt(13) if num_cards >= 4 else Pt(16)
                    p_num.font.bold = True
                    p_num.font.color.rgb = c_accent
                    p_num.space_after = Pt(6)

                    # Card Title
                    p_ctitle = ctf.add_paragraph()
                    p_ctitle.text = card.get("title", f"Pillar {c_i+1}")
                    p_ctitle.font.name = "Segoe UI"
                    p_ctitle.font.size = Pt(12) if num_cards >= 4 else Pt(15)
                    p_ctitle.font.bold = True
                    p_ctitle.font.color.rgb = c_text_main
                    p_ctitle.space_after = Pt(8)

                    # Card Description / Points
                    desc = card.get("description", "")
                    if desc:
                        p_cdesc = ctf.add_paragraph()
                        p_cdesc.text = desc
                        p_cdesc.font.name = "Segoe UI"
                        p_cdesc.font.size = Pt(9.5) if num_cards >= 4 else Pt(11)
                        p_cdesc.font.color.rgb = c_text_muted
                        p_cdesc.space_after = Pt(6)

                    for point in card.get("points", []):
                        p_p = ctf.add_paragraph()
                        p_p.text = f"• {point}"
                        p_p.font.name = "Segoe UI"
                        p_p.font.size = Pt(9) if num_cards >= 4 else Pt(10.5)
                        p_p.font.color.rgb = c_text_muted
                        p_p.space_after = Pt(4)

            elif bullets:
                # 2-column or list layout
                box = slide.shapes.add_textbox(Inches(1.0), Inches(2.2), Inches(11.3), Inches(4.5))
                btf = box.text_frame
                btf.word_wrap = True

                for b_i, b in enumerate(bullets):
                    p = btf.paragraphs[0] if b_i == 0 else btf.add_paragraph()
                    p.text = f"▸  {b}"
                    p.font.name = "Segoe UI"
                    p.font.size = Pt(14)
                    p.font.color.rgb = c_text_main
                    p.space_after = Pt(14)

            # Footer on each slide
            ft_box = slide.shapes.add_textbox(Inches(0.9), Inches(6.9), Inches(11.5), Inches(0.4))
            ftf = ft_box.text_frame
            p_ft = ftf.paragraphs[0]
            p_ft.text = f"{topic.upper()}  |  SLIDE {slide_idx} OF {len(slides_data)}"
            p_ft.font.name = "Segoe UI"
            p_ft.font.size = Pt(8.5)
            p_ft.font.color.rgb = c_text_muted

        try:
            prs.save(str(out_path))
        except (PermissionError, OSError):
            stem = out_path.stem
            ext = out_path.suffix
            parent = out_path.parent
            for i in range(2, 100):
                candidate = parent / f"{stem}_v{i}{ext}"
                try:
                    prs.save(str(candidate))
                    out_path = candidate
                    logger.warning(f"File locked during save. Saved presentation as '{out_path.name}'.")
                    break
                except (PermissionError, OSError):
                    continue
            else:
                raise
        file_size = out_path.stat().st_size

        doc_id = f"doc-pptx-{uuid.uuid4().hex[:8]}"
        try:
            save_generated_document(
                doc_id=doc_id,
                filename=out_path.name,
                file_path=str(out_path),
                file_type="PPTX",
                topic=topic,
                size_bytes=file_size,
                task_id=task_id
            )
        except Exception as e:
            logger.warning(f"Could not register presentation in DB: {e}")

        logger.info(f"Generated PowerPoint presentation: {out_path} ({file_size} bytes)")
        return {
            "success": True,
            "doc_id": doc_id,
            "path": str(out_path),
            "file_path": str(out_path),
            "filename": out_path.name,
            "topic": topic,
            "slides_count": len(slides_data),
            "file_size": file_size,
            "message": f"PowerPoint presentation '{out_path.name}' created with {len(slides_data)} styled slides."
        }

    # =========================================================================
    # 2. EXECUTIVE PDF REPORT GENERATOR (.pdf)
    # =========================================================================
    def create_pdf_report(
        self,
        title: str,
        filename: Optional[str] = None,
        sections: Optional[List[Dict[str, Any]]] = None,
        executive_summary: Optional[str] = None,
        task_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates a publication-grade PDF report with cover header,
        styled callout box, structured multi-section text, data tables, and dynamic footer.
        """
        if not filename:
            clean_title = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            filename = f"{clean_title[:30]}_Report.pdf"

        out_path = self._resolve_output_path(filename, ".pdf")

        total_words = sum(len(str(s.get("text") or s.get("content") or s.get("body") or "").split()) for s in (sections or []))
        is_assistant_topic = any(w in (title + " " + (filename or "")).lower() for w in ["functionality", "features", "assistant", "system", "architecture", "guide", "overview", "3 page"])
        if not sections or (total_words < 120 and is_assistant_topic):
            sections = self._generate_default_pdf_sections(title)
        if not executive_summary:
            executive_summary = (
                f"This comprehensive executive report provides an in-depth operational and architectural analysis "
                f"of {title}. It explores foundational methodologies, core performance benchmarks, implementation "
                f"strategies, and future growth trajectories."
            )

        doc = SimpleDocTemplate(
            str(out_path),
            pagesize=letter,
            leftMargin=46,
            rightMargin=46,
            topMargin=46,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        style_title = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=6
        )

        style_subtitle = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=16
        )

        style_h1 = ParagraphStyle(
            "Heading1_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#0284c7"),
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True
        )

        style_h2 = ParagraphStyle(
            "Heading2_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=11.5,
            leading=15,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=10,
            spaceAfter=4,
            keepWithNext=True
        )

        style_body = ParagraphStyle(
            "Body_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8
        )

        style_bullet = ParagraphStyle(
            "Bullet_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
            leftIndent=14,
            spaceAfter=4
        )

        style_callout = ParagraphStyle(
            "Callout_Custom",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#0f172a")
        )

        def _safe_rl(val: Any) -> str:
            s = str(val) if val is not None else ""
            # Escape HTML/XML entities so ReportLab paraparser never crashes on unescaped <, >, &
            return html.escape(s)

        story = []

        # 1. Document Header
        story.append(Paragraph(_safe_rl(title), style_title))
        meta_line = f"Publication Date: {datetime.now().strftime('%B %d, %Y')}   |   Status: Verified Report   |   System: AI OS Platform"
        story.append(Paragraph(_safe_rl(meta_line), style_subtitle))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceBefore=0, spaceAfter=14))

        # 2. Executive Summary Callout Box
        summary_inner = [
            [Paragraph("<b>EXECUTIVE SUMMARY</b>", ParagraphStyle("ES_H", fontName="Helvetica-Bold", fontSize=10, textColor=colors.HexColor("#0369a1")))],
            [Paragraph(_safe_rl(executive_summary), style_callout)]
        ]
        summary_table = Table(summary_inner, colWidths=[520])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#f0f9ff")),
            ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#bae6fd")),
            ('LINELEFT', (0,0), (0,-1), 3.5, colors.HexColor("#0284c7")),
            ('PADDING', (0,0), (-1,-1), 8),
            ('BOTTOMPADDING', (0,0), (-1,0), 4),
        ]))
        story.append(summary_table)
        story.append(Spacer(1, 14))

        # 3. Dynamic Sections
        for sec_idx, sec in enumerate(sections):
            heading = sec.get("heading") or sec.get("title") or f"Section {sec_idx + 1}"
            story.append(Paragraph(_safe_rl(heading), style_h1))
            sec_text = sec.get("text") or sec.get("content") or sec.get("body") or sec.get("description") or ""
            if sec_text:
                for line in sec_text.split("\n"):
                    line = line.strip()
                    if not line:
                        continue
                    if line.startswith("•") or line.startswith("- ") or line.startswith("* "):
                        clean_bullet = line.lstrip("•-* ").strip()
                        story.append(Paragraph(f"•  {_safe_rl(clean_bullet)}", style_bullet))
                    else:
                        story.append(Paragraph(_safe_rl(line), style_body))

            # Bullets if any
            for b in sec.get("bullets") or sec.get("items") or []:
                story.append(Paragraph(f"•  {_safe_rl(b)}", style_bullet))

            # Metric Table if any
            table_data = sec.get("table", None)
            if table_data and len(table_data) > 1:
                story.append(Spacer(1, 4))
                t_rows = []
                for row_idx, r in enumerate(table_data):
                    t_row = []
                    for c in r:
                        font_n = "Helvetica-Bold" if row_idx == 0 else "Helvetica"
                        text_c = colors.HexColor("#ffffff") if row_idx == 0 else colors.HexColor("#1e293b")
                        p = Paragraph(_safe_rl(c), ParagraphStyle(f"T_{row_idx}", fontName=font_n, fontSize=8.5, leading=11, textColor=text_c))
                        t_row.append(p)
                    t_rows.append(t_row)

                num_cols = len(table_data[0])
                col_w = 520 / num_cols
                rep_table = Table(t_rows, colWidths=[col_w] * num_cols)
                rep_table.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#0f172a")),
                    ('ALIGN', (0,0), (-1,-1), 'LEFT'),
                    ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                    ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#cbd5e1")),
                    ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.HexColor("#ffffff"), colors.HexColor("#f8fafc")]),
                    ('PADDING', (0,0), (-1,-1), 5),
                ]))
                story.append(rep_table)
                story.append(Spacer(1, 8))

            if sec.get("page_break_after") or (len(sections) == 3 and sec_idx < len(sections) - 1):
                story.append(PageBreak())

        doc.build(story, canvasmaker=NumberedCanvas)
        file_size = out_path.stat().st_size

        doc_id = f"doc-pdf-{uuid.uuid4().hex[:8]}"
        try:
            save_generated_document(
                doc_id=doc_id,
                filename=out_path.name,
                file_path=str(out_path),
                file_type="PDF",
                topic=title,
                size_bytes=file_size,
                task_id=task_id
            )
        except Exception as e:
            logger.warning(f"Could not register PDF in DB: {e}")

        logger.info(f"Generated PDF report: {out_path} ({file_size} bytes)")
        return {
            "success": True,
            "doc_id": doc_id,
            "path": str(out_path),
            "file_path": str(out_path),
            "filename": out_path.name,
            "title": title,
            "file_size": file_size,
            "message": f"Executive PDF report '{out_path.name}' created with publication-grade formatting."
        }

    # =========================================================================
    # 3. MICROSOFT WORD DOCUMENT GENERATOR (.docx)
    # =========================================================================
    def create_word_document(
        self,
        topic: str,
        filename: Optional[str] = None,
        sections: Optional[List[Dict[str, Any]]] = None,
        theme: str = "enterprise",
        task_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates a publication-grade Microsoft Word document (.docx) with structured
        executive summary, domain sections, formatted benchmark tables, and bullet points.
        """
        if not HAS_DOCX:
            return {"success": False, "error": "python-docx package is not installed"}

        if not filename:
            clean = "".join(c for c in topic if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            filename = f"{clean[:30]}_Document.docx"

        out_path = self._resolve_output_path(filename, ".docx")
        doc = DocxDocument()

        # Page margins
        for sec in doc.sections:
            sec.top_margin = sec.bottom_margin = DocxInches(1)
            sec.left_margin = sec.right_margin = DocxInches(1.1)

        # Title
        p_title = doc.add_paragraph()
        r_title = p_title.add_run(topic.title())
        r_title.font.name = "Calibri"
        r_title.font.size = DocxPt(26)
        r_title.font.bold = True
        r_title.font.color.rgb = DocxRGB(0x0F, 0x17, 0x2A)  # Deep Slate
        p_title.paragraph_format.space_after = DocxPt(4)

        # Subtitle / Date
        p_sub = doc.add_paragraph()
        r_sub = p_sub.add_run(f"Enterprise Intelligence Dossier  •  {datetime.now().strftime('%B %d, %Y')}")
        r_sub.font.name = "Calibri"
        r_sub.font.size = DocxPt(11)
        r_sub.font.color.rgb = DocxRGB(0x25, 0x63, 0xEB)  # Accent Blue
        p_sub.paragraph_format.space_after = DocxPt(16)

        sections = sections or self._generate_default_docx_sections(topic)

        for sec_data in sections:
            heading = sec_data.get("heading")
            if heading:
                p_h = doc.add_paragraph()
                r_h = p_h.add_run(heading)
                r_h.font.name = "Calibri"
                r_h.font.size = DocxPt(15)
                r_h.font.bold = True
                r_h.font.color.rgb = DocxRGB(0x1E, 0x3A, 0x8A)
                p_h.paragraph_format.space_before = DocxPt(14)
                p_h.paragraph_format.space_after = DocxPt(4)

            text = sec_data.get("text") or sec_data.get("content")
            code_block = sec_data.get("code")

            if not code_block and text and ("#include" in text or "int main(" in text or "```" in text or "def " in text or "class " in text):
                code_match = re.search(r"```(?:[a-zA-Z0-9_\-]+)?\n([\s\S]*?)```", text)
                if code_match:
                    code_block = code_match.group(1).strip()
                    text = text[:code_match.start()].strip()
                elif "#include" in text or "int main(" in text:
                    code_block = text
                    text = ""

            if text:
                p_t = doc.add_paragraph()
                r_t = p_t.add_run(text)
                r_t.font.name = "Calibri"
                r_t.font.size = DocxPt(11)
                r_t.font.color.rgb = DocxRGB(0x33, 0x41, 0x55)
                p_t.paragraph_format.space_after = DocxPt(6)
                p_t.paragraph_format.line_spacing = 1.15

            if code_block:
                table_code = doc.add_table(rows=1, cols=1)
                table_code.alignment = WD_TABLE_ALIGNMENT.CENTER
                table_code.autofit = True
                cell = table_code.cell(0, 0)
                shading = parse_xml(r'<w:shd {} w:fill="0F172A"/>'.format(nsdecls('w')))
                cell._tc.get_or_add_tcPr().append(shading)
                p_code = cell.paragraphs[0]
                p_code.paragraph_format.space_before = DocxPt(6)
                p_code.paragraph_format.space_after = DocxPt(6)
                p_code.paragraph_format.line_spacing = 1.05
                r_code = p_code.add_run(code_block)
                r_code.font.name = "Consolas"
                r_code.font.size = DocxPt(9.5)
                r_code.font.color.rgb = DocxRGB(0x38, 0xBD, 0xF8)
                p_sp = doc.add_paragraph()
                p_sp.paragraph_format.space_after = DocxPt(6)

            bullets = sec_data.get("bullets", [])
            for b in bullets:
                p_b = doc.add_paragraph(style='List Bullet')
                r_b = p_b.add_run(b)
                r_b.font.name = "Calibri"
                r_b.font.size = DocxPt(10.5)
                r_b.font.color.rgb = DocxRGB(0x33, 0x41, 0x55)
                p_b.paragraph_format.space_after = DocxPt(3)

            table_data = sec_data.get("table")
            if table_data and len(table_data) > 1:
                table = doc.add_table(rows=len(table_data), cols=len(table_data[0]))
                table.alignment = WD_TABLE_ALIGNMENT.CENTER
                table.autofit = True

                for r_idx, row in enumerate(table_data):
                    for c_idx, cell_val in enumerate(row):
                        cell = table.cell(r_idx, c_idx)
                        cell.text = str(cell_val)
                        cell_p = cell.paragraphs[0]
                        cell_r = cell_p.runs[0]
                        cell_r.font.name = "Calibri"
                        cell_r.font.size = DocxPt(9.5)

                        if r_idx == 0:
                            cell_r.font.bold = True
                            cell_r.font.color.rgb = DocxRGB(0xFF, 0xFF, 0xFF)
                            shading = parse_xml(r'<w:shd {} w:fill="0F172A"/>'.format(nsdecls('w')))
                            cell._tc.get_or_add_tcPr().append(shading)
                        else:
                            cell_r.font.color.rgb = DocxRGB(0x1E, 0x29, 0x3B)
                            if r_idx % 2 == 1:
                                shading = parse_xml(r'<w:shd {} w:fill="F8FAFC"/>'.format(nsdecls('w')))
                                cell._tc.get_or_add_tcPr().append(shading)

                p_sp = doc.add_paragraph()
                p_sp.paragraph_format.space_after = DocxPt(8)

        try:
            doc.save(str(out_path))
        except (PermissionError, OSError):
            stem = out_path.stem
            ext = out_path.suffix
            parent = out_path.parent
            for i in range(2, 100):
                candidate = parent / f"{stem}_v{i}{ext}"
                try:
                    doc.save(str(candidate))
                    out_path = candidate
                    logger.warning(f"File locked during save. Saved Word document as '{out_path.name}'.")
                    break
                except (PermissionError, OSError):
                    continue
            else:
                raise
        file_size = out_path.stat().st_size
        doc_id = f"doc-docx-{uuid.uuid4().hex[:8]}"

        try:
            save_generated_document(
                doc_id=doc_id,
                filename=out_path.name,
                file_path=str(out_path),
                file_type="DOCX",
                topic=topic,
                size_bytes=file_size,
                task_id=task_id
            )
        except Exception as e:
            logger.warning(f"Could not register DOCX in DB: {e}")

        logger.info(f"Generated Word document: {out_path} ({file_size} bytes)")
        return {
            "success": True,
            "doc_id": doc_id,
            "path": str(out_path),
            "file_path": str(out_path),
            "filename": out_path.name,
            "topic": topic,
            "sections_count": len(sections),
            "file_size": file_size,
            "message": f"Word document '{out_path.name}' created with publication-grade formatting."
        }

